import { copyPose } from './world-api.mjs';
import { initialPose, viewCamera } from './world-model.mjs';
import { MOUSE, TOUCH } from 'three';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';
import { spatialPattern, spatialPatterns, spatialGroupings } from './spatial-patterns.mjs';
import { spacingPresets } from './object-presentation.mjs';
import { bindWorldEvents } from './world-events.mjs';
export function setupWorldView(ctx) {
    if (ctx.restored?.target !== ctx.target)
        ctx.restored = null;
    spatialPattern(ctx.objects, ctx.relations, ctx.restored?.presentation ?? { pattern: ctx.pattern });
    ctx.pose = ctx.restored ? copyPose(ctx.restored) : initialPose();
    ctx.document = ctx.host.ownerDocument;
    ctx.browser = ctx.document.defaultView;
    if (!ctx.browser)
        throw Error('WorldDocumentUnavailable');
    ctx.window = ctx.browser;
    ctx.controller = new AbortController();
    ctx.signal = ctx.controller.signal;
    ctx.make = (tag, className, text) => { const n = ctx.document.createElement(tag); n.className = className; if (text)
        n.textContent = text; return n; };
    ctx.wrap = ctx.make('section', 'mind-world');
    ctx.canvas = ctx.make('canvas', 'world-canvas');
    ctx.labels = ctx.make('div', 'world-labels');
    ctx.hud = ctx.make('div', 'world-hud');
    ctx.canvas.tabIndex = 0;
    ctx.canvas.setAttribute('aria-label', 'Explore your world. W A S D or arrows to walk. Drag to look. E to interact. M for Map. Q to mark.');
    ctx.wrap.setAttribute('aria-label', 'Thinking garden');
    ctx.wrap.dataset.presentationOnly = 'true';
    ctx.aim = ctx.make('span', 'world-aim', '+');
    ctx.hint = ctx.make('button', 'world-hint');
    ctx.status = ctx.make('p', 'world-gpu-error');
    ctx.aim.setAttribute('aria-hidden', 'true');
    ctx.status.hidden = true;
    ctx.status.setAttribute('role', 'alert');
    ctx.tools = ctx.make('div', 'world-controls');
    ctx.nearby = ctx.make('details', 'world-nearby');
    ctx.list = ctx.make('div', 'world-directory');
    ctx.summary = ctx.make('summary', '', 'In this space');
    ctx.hint.type = 'button';
    ctx.nearby.append(ctx.summary, ctx.list);
    ctx.hud.append(ctx.hint, ctx.tools, ctx.nearby);
    ctx.wrap.append(ctx.canvas, ctx.labels, ctx.aim, ctx.hud, ctx.status);
    ctx.host.prepend(ctx.wrap);
    ctx.roleStatus = (value, id) => ctx.activityPresentation.describeRole?.(value, id) ?? null;
    ctx.engine = ctx.activityPresentation.createView?.(ctx.document, ctx.wrap) ?? { panel: ctx.document.createElement('div'), update() { } };
    ctx.engine.panel.hidden = ctx.pattern === 'garden';
    ctx.spacing = 'balanced';
    ctx.placedSpacing = null;
    ctx.model = { items: [], relations: [] };
    ctx.gpu = null;
    ctx.geometry = null;
    ctx.actorRanges = [];
    ctx.closed = false;
    ctx.attached = true;
    ctx.lost = false;
    ctx.dirty = true;
    ctx.frame = null;
    ctx.motionTimer = null;
    ctx.last = 0;
    ctx.frames = 0;
    ctx.drag = null;
    ctx.hovered = null;
    ctx.paused = false;
    ctx.zoom = 1;
    ctx.projected = [];
    ctx.labelNodes = new Map();
    ctx.directoryNodes = new Map();
    ctx.geometryKey = null;
    ctx.uploads = 0;
    ctx.initializations = 0;
    ctx.navigation = 'overview';
    ctx.needsFit = !ctx.restored;
    ctx.lastWidth = 0;
    ctx.lastHeight = 0;
    ctx.selectedId = null;
    ctx.markedId = null;
    ctx.recent = new Map();
    ctx.poses = new Map();
    ctx.fittedPopulation = Boolean(ctx.restored?.populated);
    ctx.sourceObjects = [];
    ctx.sourceRelations = ctx.relations;
    ctx.view = ctx.restored?.presentation ?? { pattern: ctx.pattern, groupBy: 'declared', group: null, page: 0 };
    ctx.projection = null;
    ctx.wrap.dataset.target = ctx.target ?? '';
    ctx.bubble = ctx.make('aside', 'world-conversation');
    ctx.bubble.hidden = true;
    ctx.bubble.setAttribute('role', 'dialog');
    ctx.bubble.tabIndex = -1;
    ctx.wrap.append(ctx.bubble);
    ctx.conversationId = null;
    ctx.returnFocus = null;
    ctx.anchorId = null;
    ctx.shell = ctx.host.closest('.delivery-shell');
    ctx.map = ctx.make('details', 'world-map');
    ctx.mapList = ctx.make('div', 'world-map-list');
    ctx.mapNote = ctx.make('small', '');
    ctx.mapButton = ctx.make('button', '', 'Mark selected');
    ctx.mapButton.type = 'button';
    ctx.map.append(ctx.make('summary', '', 'Map'), ctx.mapNote, ctx.mapList, ctx.mapButton);
    ctx.hud.append(ctx.map);
    ctx.keys = new Set();
    ctx.inputBlocked = () => ctx.paused || ctx.nearby.open || ctx.map.open || !ctx.bubble.hidden || !ctx.document.hasFocus() || Boolean(ctx.document.querySelector('.frame-panel:not([hidden])'));
    ctx.button = (text, label, action, parent = ctx.tools) => { const b = ctx.make('button', '', text); b.type = 'button'; b.setAttribute('aria-label', label); b.addEventListener('click', action, { signal: ctx.signal }); parent.append(b); return b; };
    ctx.inspect = ctx.button('Inspect', 'Inspect aimed object', () => ctx.activate(ctx.hovered));
    ctx.reset = ctx.button('⛶', 'View all', () => ctx.overview());
    ctx.reset.dataset.overviewControl = 'true';
    ctx.settings = ctx.make('div', 'world-layout');
    ctx.breadcrumb = ctx.make('div', 'world-breadcrumb');
    ctx.location = ctx.make('output', '');
    ctx.pagination = ctx.make('div', 'world-pagination');
    ctx.selector = (label, entries, change) => { const field = ctx.make('label', '', label), select = ctx.make('select', ''); select.setAttribute('aria-label', label); for (const [id, title] of entries) {
        const option = ctx.make('option', '', title);
        option.value = id;
        select.append(option);
    } select.addEventListener('change', () => change(select.value), { signal: ctx.signal }); field.append(select); ctx.settings.append(field); return select; };
    ctx.navigationSelect = ctx.selector('Navigation', [['overview', 'Overview'], ['explore', 'Walk through world']], value => { ctx.navigation = value; ctx.walk.hidden = value !== 'explore'; if (value === 'overview')
        ctx.overview();
    else {
        ctx.pose = { ...initialPose(), cameraMode: 'third-person' };
        ctx.stopInput();
        ctx.invalidate();
    } });
    ctx.patternSelect = ctx.selector('Spatial layout', spatialPatterns, value => { ctx.view = { ...ctx.view, pattern: value, group: null, page: 0 }; ctx.needsFit = true; ctx.update(ctx.sourceObjects, ctx.sourceRelations); });
    ctx.groupSelect = ctx.selector('Group by', spatialGroupings, value => { ctx.view = { ...ctx.view, groupBy: value, group: null, page: 0 }; ctx.needsFit = true; ctx.update(ctx.sourceObjects, ctx.sourceRelations); });
    ctx.selector('Object spacing', Object.keys(spacingPresets).map(id => [id, id[0].toUpperCase() + id.slice(1)]), value => { ctx.spacing = value; ctx.needsFit = true; ctx.update(ctx.sourceObjects, ctx.sourceRelations); }).value = ctx.spacing;
    ctx.legend = ctx.make('p', 'world-legend', ctx.pattern === 'garden' ? 'People are shown here. Their published information is available inside each person’s panel; movement is visual only.' : 'Placement follows layout settings; only lines represent declared relationships.');
    ctx.settings.append(ctx.legend);
    ctx.back = ctx.button('All shelves', 'Return to all shelves', () => { ctx.view = { ...ctx.view, group: null, page: 0 }; ctx.needsFit = true; ctx.update(ctx.sourceObjects, ctx.sourceRelations); }, ctx.breadcrumb);
    ctx.breadcrumb.append(ctx.location);
    ctx.hud.append(ctx.breadcrumb);
    ctx.nearby.append(ctx.pagination, ctx.settings);
    ctx.previous = ctx.button('Previous', 'Previous objects', () => { ctx.view = { ...ctx.view, page: ctx.view.page - 1 }; ctx.needsFit = true; ctx.update(ctx.sourceObjects, ctx.sourceRelations); }, ctx.pagination);
    ctx.pageCount = ctx.make('output', '');
    ctx.pagination.append(ctx.pageCount);
    ctx.nextPage = ctx.button('Next', 'Next objects', () => { ctx.view = { ...ctx.view, page: ctx.view.page + 1 }; ctx.needsFit = true; ctx.update(ctx.sourceObjects, ctx.sourceRelations); }, ctx.pagination);
    ctx.updates = ctx.make('details', 'world-updates');
    ctx.updatesTitle = ctx.make('summary', '', 'Observed changes');
    ctx.updateList = ctx.make('div', '');
    ctx.updateHelp = ctx.make('p', '', 'Changes observed while this view is open. Not execution history.');
    ctx.updates.setAttribute('aria-label', 'Changes in this view');
    ctx.updates.append(ctx.updatesTitle, ctx.updateHelp, ctx.updateList);
    ctx.hud.append(ctx.updates);
    ctx.query = ctx.make('input', '');
    ctx.noMatches = ctx.make('p', '', 'No matching objects in this scope.');
    ctx.query.type = 'search';
    ctx.query.maxLength = 128;
    ctx.query.placeholder = 'Find in this space';
    ctx.query.setAttribute('aria-label', 'Find in this space');
    ctx.noMatches.hidden = true;
    ctx.nearby.insertBefore(ctx.query, ctx.list);
    ctx.nearby.insertBefore(ctx.noMatches, ctx.list);
    ctx.orbitCamera = viewCamera(ctx.pose, 1);
    ctx.orbit = new OrbitControls(ctx.orbitCamera, ctx.canvas);
    ctx.orbit.enableDamping = false;
    ctx.orbit.autoRotate = false;
    ctx.orbit.enableRotate = false;
    ctx.orbit.screenSpacePanning = true;
    ctx.orbit.minDistance = 3;
    ctx.orbit.maxDistance = 1500;
    ctx.orbit.mouseButtons.LEFT = MOUSE.PAN;
    ctx.orbit.touches.ONE = TOUCH.PAN;
    ctx.orbit.touches.TWO = TOUCH.DOLLY_PAN;
    ctx.syncing = false;
    ctx.enableOrbit = () => { ctx.orbit.enabled = ctx.navigation === 'overview' && !ctx.inputBlocked(); if (ctx.orbit.enabled)
        ctx.syncOrbit(); };
    ctx.setText = (node, value) => { if (node.textContent !== value)
        node.textContent = value ?? ''; };
    ctx.walk = ctx.make('div', 'world-walk');
    ctx.walk.hidden = true;
    ctx.walk.setAttribute('role', 'group');
    ctx.walk.setAttribute('aria-label', 'Walk controls');
    ctx.hud.append(ctx.walk);
    ctx.resize = new ctx.window.ResizeObserver(ctx.fitViewport);
    ctx.resize.observe(ctx.host);
    bindWorldEvents(ctx);
    ctx.update(ctx.objects, ctx.relations);
    ctx.initialize();
}
